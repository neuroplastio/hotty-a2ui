// Command gen writes the cells width table, widths_gen.go, from the
// Unicode Character Database at one version: `go generate` in
// rendition/cells runs it. It fetches three UCD files and checks each
// against its pinned SHA-256, so the table changes only when the version
// here does.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"slices"
	"strconv"
	"strings"
)

// version is the Unicode version of the table. clipperhouse/uax29, which
// segments grapheme clusters, must be at the same one.
const version = "17.0.0"

var files = []struct{ path, sha256 string }{
	{"ucd/EastAsianWidth.txt", "ea7ce50f3444a050333448dffef1cadd9325af55cbb764b4a2280faf52170a33"},
	{"ucd/emoji/emoji-data.txt", "2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b"},
	{"ucd/extracted/DerivedGeneralCategory.txt", "d62e5bab70ca74f099343f71224fa051cb1fdd61a1ab45c0488c44cfc0b6102e"},
}

func main() {
	out := "widths_gen.go"
	if len(os.Args) > 1 {
		out = os.Args[1]
	}
	data := map[string][]byte{}
	for _, f := range files {
		b, err := fetch("https://www.unicode.org/Public/" + version + "/" + f.path)
		if err != nil {
			log.Fatal(err)
		}
		sum := sha256.Sum256(b)
		if got := hex.EncodeToString(sum[:]); got != f.sha256 {
			log.Fatalf("%s: sha256 %s, pinned %s", f.path, got, f.sha256)
		}
		data[f.path] = b
	}

	var wide, zero, pict, presentation set
	for _, l := range lines(data["ucd/EastAsianWidth.txt"]) {
		if l.value == "W" || l.value == "F" {
			wide.add(l.lo, l.hi)
		}
	}
	for _, l := range lines(data["ucd/emoji/emoji-data.txt"]) {
		switch l.value {
		case "Extended_Pictographic":
			pict.add(l.lo, l.hi)
		case "Emoji_Presentation":
			presentation.add(l.lo, l.hi)
		}
	}
	for r := range presentation.runes() {
		if pict.has(r) {
			wide.add(r, r)
		}
	}
	for _, l := range lines(data["ucd/extracted/DerivedGeneralCategory.txt"]) {
		switch l.value {
		case "Mn", "Mc", "Me", "Cf":
			zero.add(l.lo, l.hi)
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/gen from the Unicode Character Database %s; DO NOT EDIT.\n\n", version)
	b.WriteString("package cells\n\n")
	b.WriteString("// UnicodeVersion is the version of the width table, and of the grapheme\n")
	b.WriteString("// clusters it measures (clipperhouse/uax29).\n")
	fmt.Fprintf(&b, "const UnicodeVersion = %q\n\n", version)
	table(&b, "wide", "are the code points of width 2: East_Asian_Width W or F, and\n// Extended_Pictographic with Emoji_Presentation.", wide)
	table(&b, "zero", "are the code points of width 0: General_Category Mn, Mc, Me and Cf\n// (marks; ZWJ and the other format controls; the variation selectors).", zero)
	table(&b, "pictographic", "is Extended_Pictographic: an emoji ZWJ sequence starts with one.", pict)
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func fetch(url string) ([]byte, error) {
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

type line struct {
	lo, hi rune
	value  string
}

// lines reads a UCD file's data lines: "lo..hi ; value # comment".
func lines(b []byte) []line {
	var out []line
	sc := bufio.NewScanner(bytes.NewReader(b))
	for sc.Scan() {
		s, _, _ := strings.Cut(sc.Text(), "#")
		cps, value, ok := strings.Cut(s, ";")
		if !ok {
			continue
		}
		lo, hi, isRange := strings.Cut(strings.TrimSpace(cps), "..")
		if !isRange {
			hi = lo
		}
		l, err1 := strconv.ParseUint(lo, 16, 32)
		h, err2 := strconv.ParseUint(hi, 16, 32)
		if err1 != nil || err2 != nil {
			log.Fatalf("bad line %q", sc.Text())
		}
		out = append(out, line{rune(l), rune(h), strings.TrimSpace(value)})
	}
	return out
}

// set is a set of code points as sorted, merged ranges.
type set struct{ r [][2]rune }

func (s *set) add(lo, hi rune) {
	s.r = append(s.r, [2]rune{lo, hi})
	slices.SortFunc(s.r, func(a, b [2]rune) int { return int(a[0] - b[0]) })
	merged := s.r[:1]
	for _, x := range s.r[1:] {
		last := &merged[len(merged)-1]
		if x[0] <= last[1]+1 {
			last[1] = max(last[1], x[1])
			continue
		}
		merged = append(merged, x)
	}
	s.r = merged
}

func (s *set) has(r rune) bool {
	_, found := slices.BinarySearchFunc(s.r, r, func(x [2]rune, r rune) int {
		switch {
		case x[1] < r:
			return -1
		case x[0] > r:
			return 1
		}
		return 0
	})
	return found
}

func (s *set) runes() func(func(rune) bool) {
	return func(yield func(rune) bool) {
		for _, x := range s.r {
			for r := x[0]; r <= x[1]; r++ {
				if !yield(r) {
					return
				}
			}
		}
	}
}

func table(b *bytes.Buffer, name, doc string, s set) {
	fmt.Fprintf(b, "// %s %s\nvar %s = table{\n", name, doc, name)
	for i, x := range s.r {
		fmt.Fprintf(b, "{0x%04X, 0x%04X},", x[0], x[1])
		if i%4 == 3 {
			b.WriteByte('\n')
		}
	}
	b.WriteString("\n}\n\n")
}
